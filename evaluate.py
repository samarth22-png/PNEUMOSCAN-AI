"""
evaluate.py
Comprehensive model evaluation script.
Generates: confusion matrix, ROC curve, PR curve, Grad-CAM gallery, evaluation report.

Usage:
    python evaluate.py --config configs/config.yaml --checkpoint outputs/models/best_model.pth
    python evaluate.py --config configs/config.yaml --checkpoint outputs/models/best_model.pth --gradcam
"""

import argparse
import json
from pathlib import Path

import numpy as np
import torch
from tqdm import tqdm

from src.dataset.dataloader import get_dataloaders
from src.dataset.transforms import get_val_transforms
from src.evaluation.confusion_matrix import plot_confusion_matrix, print_classification_report
from src.evaluation.grad_cam import GradCAM, GradCAMPlusPlus
from src.evaluation.roc_auc import plot_precision_recall_curve, plot_roc_curve
from src.training.metrics import compute_metrics, format_metrics
from src.utils.helpers import denormalise_image, get_device, load_config, seed_everything
from src.utils.logger import get_logger

logger = get_logger(__name__, log_file="outputs/logs/evaluate.log")


def load_model(config: dict, checkpoint_path: str, device: torch.device):
    """Load model from checkpoint."""
    from train import build_model
    model = build_model(config, device)
    checkpoint = torch.load(checkpoint_path, map_location=device)
    model.load_state_dict(checkpoint["model_state_dict"])
    model.eval()
    logger.info(f"Loaded model from: {checkpoint_path}")
    logger.info(f"Checkpoint epoch: {checkpoint.get('epoch', 'unknown')}")
    logger.info(f"Checkpoint val_acc: {checkpoint.get('val_acc', 'unknown'):.4f}")
    return model


@torch.no_grad()
def run_inference(model, loader, device, config):
    """Run inference on a DataLoader and collect predictions."""
    all_preds, all_labels, all_probs = [], [], []

    for images, labels in tqdm(loader, desc="Evaluating"):
        images = images.to(device, non_blocking=True)
        logits = model(images)
        probs = torch.softmax(logits, dim=1)
        preds = logits.argmax(dim=1)

        all_preds.extend(preds.cpu().numpy())
        all_labels.extend(labels.numpy())
        all_probs.extend(probs.cpu().numpy())

    return all_preds, all_labels, np.array(all_probs)


def generate_gradcam_gallery(model, loader, config, device, save_dir: str, max_images: int = 20):
    """Generate Grad-CAM visualisations for a batch of test images."""
    from src.models.efficientnet_model import EfficientNetTransfer
    from src.models.resnet_transfer import ResNetTransfer

    # Select target layer based on model type
    if isinstance(model, EfficientNetTransfer):
        target_layer = model.backbone.features[-1]
    elif isinstance(model, ResNetTransfer):
        target_layer = model.backbone.layer4[-1]
    else:
        # Custom CNN — use last ConvBlock
        target_layer = model.features[-1].block[-3]  # Last Conv2d

    gradcam = GradCAM(model, target_layer)
    class_names = config["data"]["class_names"]

    images_list, tensors_list = [], []
    for images, _ in loader:
        for img_tensor in images:
            original = denormalise_image(img_tensor)
            original_uint8 = (original * 255).astype(np.uint8)
            images_list.append(original_uint8)
            tensors_list.append(img_tensor.unsqueeze(0).to(device))
            if len(images_list) >= max_images:
                break
        if len(images_list) >= max_images:
            break

    gradcam.batch_visualise(
        images=images_list,
        tensors=tensors_list,
        class_names=class_names,
        save_dir=save_dir,
        max_images=max_images,
    )
    gradcam.remove_hooks()


def save_evaluation_report(metrics: dict, config: dict, save_path: str) -> None:
    """Save evaluation report as Markdown."""
    class_names = config["data"]["class_names"]
    model_name = config["model"]["name"]

    report = f"""# Evaluation Report

## Model: {model_name}
## Dataset: {config['data']['root']}

---

## Performance Metrics

| Metric | Value |
|--------|-------|
| Accuracy | {metrics.get('accuracy', 0):.4f} |
| Precision | {metrics.get('precision', 0):.4f} |
| Recall / Sensitivity | {metrics.get('sensitivity', 0):.4f} |
| Specificity | {metrics.get('specificity', 0):.4f} |
| F1 Score | {metrics.get('f1', 0):.4f} |
| F1 Weighted | {metrics.get('f1_weighted', 0):.4f} |
| ROC-AUC | {metrics.get('roc_auc', 0):.4f} |
| Avg Precision | {metrics.get('avg_precision', 0):.4f} |

## Confusion Matrix

```
{metrics.get('confusion_matrix', [])}
```

## Classes
{', '.join(class_names)}

---
*Generated by evaluate.py*
"""

    Path(save_path).parent.mkdir(parents=True, exist_ok=True)
    with open(save_path, "w") as f:
        f.write(report)
    logger.info(f"Saved evaluation report → {save_path}")


def main(args):
    config = load_config(args.config)
    seed_everything(config.get("seed", 42))
    device = get_device()

    # DataLoaders (test set)
    img_size = config["data"]["img_size"]
    val_transform = get_val_transforms(img_size=img_size)
    _, _, test_loader = get_dataloaders(config, val_transform=val_transform, train_transform=val_transform)

    # Load model
    model = load_model(config, args.checkpoint, device)

    # Run inference
    logger.info("Running inference on test set...")
    preds, labels, probs = run_inference(model, test_loader, device, config)

    # Compute metrics
    metrics = compute_metrics(
        preds, labels, probs,
        num_classes=config["data"]["num_classes"],
        class_names=config["data"]["class_names"],
    )

    logger.info(format_metrics(metrics, prefix="Test"))
    print_classification_report(labels, preds, config["data"]["class_names"])

    # Save metrics JSON
    metrics_path = Path(config["outputs"]["report_dir"]) / "test_metrics.json"
    metrics_to_save = {k: v for k, v in metrics.items() if k != "roc_curve"}
    with open(metrics_path, "w") as f:
        json.dump(metrics_to_save, f, indent=2)
    logger.info(f"Saved metrics → {metrics_path}")

    # Plots
    plot_dir = Path(config["outputs"]["plot_dir"])

    plot_confusion_matrix(
        labels, preds,
        class_names=config["data"]["class_names"],
        save_path=str(plot_dir / "confusion_matrix.png"),
        normalise=True,
    )

    plot_roc_curve(
        labels, probs,
        save_path=str(plot_dir / "roc_curve.png"),
    )

    plot_precision_recall_curve(
        labels, probs,
        save_path=str(plot_dir / "pr_curve.png"),
    )

    # Grad-CAM gallery
    if args.gradcam:
        logger.info("Generating Grad-CAM visualisations...")
        generate_gradcam_gallery(
            model, test_loader, config, device,
            save_dir=str(plot_dir / "gradcam"),
            max_images=args.gradcam_n,
        )

    # Evaluation report
    save_evaluation_report(
        metrics, config,
        save_path=str(Path(config["outputs"]["report_dir"]) / "evaluation_report.md"),
    )

    logger.info("Evaluation complete.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Evaluate CNN Medical Image Classifier")
    parser.add_argument("--config", type=str, default="configs/config.yaml")
    parser.add_argument("--checkpoint", type=str, required=True,
                        help="Path to model checkpoint (.pth)")
    parser.add_argument("--gradcam", action="store_true",
                        help="Generate Grad-CAM visualisations")
    parser.add_argument("--gradcam-n", type=int, default=20,
                        help="Number of Grad-CAM images to generate")
    args = parser.parse_args()
    main(args)
